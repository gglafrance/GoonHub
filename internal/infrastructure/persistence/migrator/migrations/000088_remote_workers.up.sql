-- Remote workers (goonhub-worker, docs/REMOTE_WORKERS.md): the registered workers, the lease
-- columns of job_history (a job leased by a remote worker carries its worker, a fencing
-- generation and a lease expiry) and the singleton worker settings (media URL secret,
-- per-phase routing between the local pools and the remote workers).

CREATE TABLE workers (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    -- sha256 (hex) of the worker token; the token itself is shown once and never stored.
    -- NULL = revoked: every call is refused until a new token is generated.
    token_hash VARCHAR(64) NULL,
    enabled BOOLEAN NOT NULL DEFAULT true,
    -- Admin asked the worker to stop claiming (running jobs finish).
    draining BOOLEAN NOT NULL DEFAULT false,
    connection_mode VARCHAR(10) NOT NULL DEFAULT 'pull'
        CONSTRAINT chk_workers_connection_mode CHECK (connection_mode IN ('pull', 'push')),
    -- Push mode: the worker endpoint, and the secret the server sends to it (generated by the
    -- worker at each start, received in register).
    push_url VARCHAR(500) NOT NULL DEFAULT '',
    push_token VARCHAR(200) NOT NULL DEFAULT '',
    -- Current session (register); calls with another session must register again.
    session_id VARCHAR(64) NOT NULL DEFAULT '',
    -- Base URL the worker used to reach the server (signed media URLs point there).
    server_url VARCHAR(500) NOT NULL DEFAULT '',
    capabilities JSONB NOT NULL DEFAULT '{}',
    -- Path mappings the worker verified (server prefix -> its read-only local mount).
    path_mappings JSONB NOT NULL DEFAULT '[]',
    -- Phases the admin allows this worker to process (intersected with its capabilities).
    allowed_phases TEXT[] NOT NULL DEFAULT '{sprites,animated_thumbnails,fingerprint}',
    -- Most jobs the worker may hold at the same time (0 = only its own slots).
    max_concurrency INTEGER NOT NULL DEFAULT 0
        CONSTRAINT chk_workers_max_concurrency CHECK (max_concurrency >= 0),
    version VARCHAR(50) NOT NULL DEFAULT '',
    hostname VARCHAR(255) NOT NULL DEFAULT '',
    os VARCHAR(20) NOT NULL DEFAULT '',
    arch VARCHAR(20) NOT NULL DEFAULT '',
    free_disk_bytes BIGINT NOT NULL DEFAULT 0,
    -- The worker said it is shutting down (heartbeat draining flag).
    worker_draining BOOLEAN NOT NULL DEFAULT false,
    last_seen_at TIMESTAMPTZ NULL,
    registered_at TIMESTAMPTZ NULL,
    jobs_completed BIGINT NOT NULL DEFAULT 0,
    jobs_failed BIGINT NOT NULL DEFAULT 0,
    leases_expired BIGINT NOT NULL DEFAULT 0,
    leases_released BIGINT NOT NULL DEFAULT 0,
    last_error TEXT NOT NULL DEFAULT '',
    last_error_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX idx_workers_token_hash ON workers (token_hash) WHERE token_hash IS NOT NULL;

-- Lease columns. A row leased by a remote worker is 'running' with worker_id set; local jobs
-- keep worker_id NULL. lease_generation is the fencing token: bumped on every claim, expiry,
-- release and cancel of a remote lease; any call with another generation is refused.
-- The attempt of a job is its retry_count.
ALTER TABLE job_history
    ADD COLUMN worker_id BIGINT NULL REFERENCES workers(id) ON DELETE SET NULL,
    ADD COLUMN lease_generation BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN lease_expires_at TIMESTAMPTZ NULL,
    ADD COLUMN last_heartbeat_at TIMESTAMPTZ NULL,
    -- Generation whose complete was committed (idempotent complete).
    ADD COLUMN committed_generation BIGINT NULL,
    -- Generation whose commit started (the fingerprint commit runs at most once per generation).
    ADD COLUMN commit_started_generation BIGINT NULL,
    ADD COLUMN input_mode VARCHAR(10) NULL,
    ADD COLUMN worker_stage VARCHAR(20) NULL,
    -- Phase parameters prepared at claim time (the complete is validated against them).
    ADD COLUMN lease_params JSONB NULL;

-- Lease expiry sweep: running remote leases by expiry.
CREATE INDEX idx_job_history_remote_lease_expiry
    ON job_history (lease_expires_at)
    WHERE status = 'running' AND worker_id IS NOT NULL;

-- Jobs of a worker (current leases, per-worker history).
CREATE INDEX idx_job_history_worker_id
    ON job_history (worker_id, status)
    WHERE worker_id IS NOT NULL;

CREATE TABLE worker_settings (
    id INTEGER PRIMARY KEY DEFAULT 1 CONSTRAINT chk_worker_settings_singleton CHECK (id = 1),
    -- HMAC secret of the signed media URLs (hex), generated at first start.
    media_secret VARCHAR(128) NOT NULL DEFAULT '',
    -- Per-phase routing override: {"sprites": "local" | "remote" | "both", ...}. A phase not
    -- listed follows the server config (workers.local_phases).
    phase_routing JSONB NOT NULL DEFAULT '{}',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO worker_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;
